/**
 * Детермінований генератор псевдовипадкових чисел (mulberry32).
 *
 * Потрібен там, де «хаос» має бути одним і тим самим при кожному рендері:
 * scrub-анімації прив'язані до прогресу скролу, тож із `Math.random()` рух
 * стрибав би при кожному перемальовуванні, а сторінка ще й розходилася б
 * між SSR і гідратацією.
 *
 * Один інстанс — одна послідовність: викликайте `next()` стільки разів,
 * скільки треба значень, і при однаковому seed отримаєте однаковий результат.
 */
export function seededRandom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
